export type LucideProps = React.SVGProps<SVGSVGElement> & {
  size?: number | string;
  strokeWidth?: number | string;
};

function createIcon(name: string, pathContent: React.ReactNode) {
  const IconComp = React.forwardRef<SVGSVGElement, LucideProps>(
    ({ size = 24, strokeWidth = 2, className = '', ...props }, ref) => (
      <svg
        ref={ref}
        width={size}
        height={size}
        viewBox="0 0 24 24"
        fill="none"
        stroke="currentColor"
        strokeWidth={strokeWidth}
        strokeLinecap="round"
        strokeLinejoin="round"
        className={`lucide lucide-${name} ${className}`}
        {...props}
      >
        {pathContent}
      </svg>
    ),
  );
  IconComp.displayName = name;
  return IconComp;
}

